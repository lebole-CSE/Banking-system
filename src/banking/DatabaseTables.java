
package banking;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

public class DatabaseTables {

    public static void createTables() {

        try (Connection connection =
                     DatabaseConnection.getConnection();
             Statement statement =
                     connection.createStatement()) {

            // Main customer table
            statement.execute("""
                CREATE TABLE IF NOT EXISTS customers (
                    customer_id VARCHAR(30) PRIMARY KEY,
                    address VARCHAR(250),
                    phone_number VARCHAR(30),
                    email VARCHAR(100),
                    customer_type VARCHAR(20) NOT NULL
                )
            """);

            // Individual customer details
            statement.execute("""
                CREATE TABLE IF NOT EXISTS individual_customers (
                    customer_id VARCHAR(30) PRIMARY KEY,
                    first_name VARCHAR(100),
                    surname VARCHAR(100),
                    national_id VARCHAR(50),
                    date_of_birth DATE,
                    FOREIGN KEY (customer_id)
                    REFERENCES customers(customer_id)
                )
            """);

            // Company customer details
            statement.execute("""
                CREATE TABLE IF NOT EXISTS company_customers (
                    customer_id VARCHAR(30) PRIMARY KEY,
                    company_name VARCHAR(150),
                    registration_number VARCHAR(50),
                    tax_identification_number VARCHAR(50),
                    business_type VARCHAR(100),
                    FOREIGN KEY (customer_id)
                    REFERENCES customers(customer_id)
                )
            """);

            // Employment details
            statement.execute("""
                CREATE TABLE IF NOT EXISTS employment_details (
                    employment_id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                    company VARCHAR(150),
                    company_address VARCHAR(250),
                    job_title VARCHAR(100)
                )
            """);

            // Accounts
            statement.execute("""
                CREATE TABLE IF NOT EXISTS accounts (
                    account_number VARCHAR(30) PRIMARY KEY,
                    branch VARCHAR(100),
                    balance DECIMAL(15,2) NOT NULL,
                    status VARCHAR(20),
                    account_type VARCHAR(20) NOT NULL,
                    customer_id VARCHAR(30) NOT NULL,
                    employment_id BIGINT,
                    FOREIGN KEY (customer_id)
                    REFERENCES customers(customer_id),
                    FOREIGN KEY (employment_id)
                    REFERENCES employment_details(employment_id)
                )
            """);

            // Transactions
            statement.execute("""
                CREATE TABLE IF NOT EXISTS transactions (
                    transaction_id VARCHAR(50) PRIMARY KEY,
                    amount DECIMAL(15,2) NOT NULL,
                    transaction_type VARCHAR(20) NOT NULL,
                    account_number VARCHAR(30) NOT NULL,
                    transaction_timestamp TIMESTAMP NOT NULL,
                    FOREIGN KEY (account_number)
                    REFERENCES accounts(account_number)
                )
            """);

            System.out.println(
                    "Database tables created successfully."
            );

        } catch (SQLException e) {
            System.out.println(
                    "Database table creation failed: "
                    + e.getMessage()
            );
            throw new RuntimeException(e);
        }
    }
}
